export const isPdfJsSupported = async () => {
  const { pdfjs } = await import("react-pdf");
  pdfjs.GlobalWorkerOptions.workerSrc = new URL(
    "pdfjs-dist/build/pdf.worker.min.mjs",
    import.meta.url,
  ).toString();

  try {
    const loadingTask = pdfjs.getDocument({
      data: new Uint8Array([
        /*
        0x25,0x50,0x44,0x46,0x2d,0x31,0x2e,0x34,0x0a, // %PDF-1.4\n
        0x31,0x20,0x30,0x20,0x6f,0x62,0x6a,0x0a,     // 1 0 obj
        0x3c,0x3c,0x2f,0x54,0x79,0x70,0x65,0x2f,0x50,0x61,0x67,0x65,0x3e,0x3e,0x0a,
        0x65,0x6e,0x64,0x6f,0x62,0x6a,0x0a,         // endobj
        0x78,0x72,0x65,0x66,0x0a,                   // xref
        0x30,0x20,0x32,0x0a,
        0x30,0x30,0x30,0x30,0x30,0x30,0x30,0x30,0x20,0x36,0x35,0x35,0x33,0x35,0x20,0x66,0x0a,
        0x30,0x30,0x30,0x30,0x30,0x30,0x30,0x31,0x20,0x30,0x30,0x30,0x30,0x30,0x20,0x6e,0x0a,
        0x74,0x72,0x61,0x69,0x6c,0x65,0x72,0x0a,
        0x3c,0x3c,0x2f,0x52,0x6f,0x6f,0x74,0x20,0x31,0x20,0x30,0x20,0x52,0x3e,0x3e,0x0a,
        0x25,0x25,0x45,0x4f,0x46,0x0a               // %%EOF
      */
      ]),
    });
    const pdf = await loadingTask.promise;
    await pdf.destroy();
    return true;
  } catch (e) {
    if (e instanceof TypeError) {
      throw e;
    }
    return true;
  }
};
